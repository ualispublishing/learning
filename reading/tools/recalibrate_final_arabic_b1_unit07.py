rows = [json.loads(line) for line in PATH.read_text(encoding='utf-8').splitlines() if line.strip()]
by = {r['id']: r for r in rows}
assert set(ADD) == set(UPDATES)
assert set(ADD).issubset(by)

lengths = []
changes = []
for pid, addition in ADD.items():
    r = by[pid]
    assert r.get('cefr') == 'B1' and r.get('unit') == 7, (pid, r.get('cefr'), r.get('unit'))
    assert addition.strip() not in r['text'], pid
    old = len(r['text'].split())
    r['text'] = r['text'].rstrip() + ' ' + addition.strip()
    new = len(r['text'].split())
    assert 220 <= new <= 350, (pid, old, new)
    if pid.endswith('-p06'):
        assert not r.get('new_lexical_targets'), (pid, r.get('new_lexical_targets'))
    r['word_count'] = new
    r['sentence_count'] = len([s for s in re.split(r'(?<=[.!؟])\s+', r['text']) if s.strip()])
    lengths.append({'passage_id': pid, 'old': old, 'new': new})

    qs = {q['id']: q for q in r['questions']}
    ans = {a['question_id']: a for a in r['answer_key']}
    for qid, (typ, prompt, tids, answer) in UPDATES[pid].items():
        q = qs[qid]
        a = ans[qid]
        changes.append({'passage_id': pid, 'question_id': qid, 'old_type': q['type'], 'new_type': typ})
        q['type'] = typ
        q['prompt'] = prompt
        q['target_ids'] = tids
        a['answer'] = answer

    r['revision'] = int(r.get('revision', 1)) + 1
    notes = r.setdefault('quality', {}).setdefault('notes', [])
    note = 'Final Pass 03/07 remediation: expanded B1 Unit 07 with perspective/repair discourse and recalibrated synthesis/grammar assessment while preserving lexical target checks.'
    if note not in notes:
        notes.append(note)

COMP = {'gist','literal_detail','sequence','cause_effect','reference_resolution','main_claim','inference','motive','stance','assumption','ambiguity_resolution','argument_relation'}
LEX = {'vocabulary_in_context','single_word_definition','cloze_transfer','register_style'}
GRAM = {'grammar_in_context','grammar_category','grammar_choice','grammar_identification','grammar_function','person_form','contrast','register_style'}
SYN = {'paraphrase','summary','synthesis','cross_text_synthesis'}

mix = {}
for pid in UPDATES:
    types = [q['type'] for q in by[pid]['questions']]
    c = {
        'comprehension_inference': sum(t in COMP for t in types),
        'lexical': sum(t in LEX for t in types),
        'grammar_style': sum(t in GRAM for t in types),
        'synthesis': sum(t in SYN for t in types),
    }
    assert c['comprehension_inference'] >= 4 and c['lexical'] >= 2 and c['grammar_style'] >= 2 and c['synthesis'] >= 1, (pid, types, c)
    mix[pid] = c

assert len(changes) == 18, len(changes)
PATH.write_text('\n'.join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in rows) + '\n', encoding='utf-8')
print(json.dumps({'level': 'B1', 'unit': 7, 'lengths': lengths, 'question_changes': len(changes), 'mix': mix}, ensure_ascii=False))
