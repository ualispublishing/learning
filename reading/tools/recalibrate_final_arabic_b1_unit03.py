rows=[json.loads(x) for x in PATH.read_text(encoding='utf-8').splitlines() if x.strip()]
by={r['id']:r for r in rows}
lengths=[]
changes=[]
for pid,addition in ADD.items():
    r=by[pid]
    assert addition.strip() not in r['text']
    old=len(r['text'].split())
    r['text']=r['text'].rstrip()+' '+addition.strip()
    new=len(r['text'].split())
    assert 220<=new<=350,(pid,old,new)
    if pid.endswith('-p06'):
        assert not r.get('new_lexical_targets'),(pid,r.get('new_lexical_targets'))
    r['word_count']=new
    r['sentence_count']=len([s for s in re.split(r'(?<=[.!؟])\s+',r['text']) if s.strip()])
    lengths.append({'passage_id':pid,'old':old,'new':new})

for pid,items in UPDATES.items():
    r=by[pid]
    qmap={q['id']:q for q in r['questions']}
    amap={a['question_id']:a for a in r['answer_key']}
    for qid,(typ,prompt,tids,answer) in items.items():
        q=qmap[qid]
        a=amap[qid]
        assert q.get('type') not in {'vocabulary_in_context','single_word_definition','grammar_function','grammar_in_context','synthesis'},(pid,qid,q)
        changes.append({'passage_id':pid,'question_id':qid,'old_type':q.get('type'),'new_type':typ})
        q['type']=typ
        q['prompt']=prompt
        q['target_ids']=tids
        a['answer']=answer
    r['revision']=int(r.get('revision',1))+1
    notes=r.setdefault('quality',{}).setdefault('notes',[])
    note='Final Pass 03/07 remediation: expanded B1 Unit 03 with topic-faithful discourse and recalibrated synthesis/grammar assessment while preserving lexical target checks.'
    if note not in notes:
        notes.append(note)

