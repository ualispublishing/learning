#!/usr/bin/env python3
"""Whole-French final audit: independent multi-pass review of all 360 passages.

This is intentionally stricter and broader than the per-unit generation seals.
It is hash-bound to the live canonical corpus and emits one artifact containing
>=10 independent audit lenses.  It never edits canonical content.
"""
from __future__ import annotations

import hashlib
import json
import re
import statistics
import subprocess
import sys
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

from jsonschema import Draft202012Validator

R = Path(__file__).resolve().parents[2]
READING = R / 'reading'
FRENCH = READING / 'french'
SCHEMA = READING / 'schema/passage.schema.json'
OUT = READING / 'audit/french_final_whole_audit.json'
LEVELS = ['a1', 'a2', 'b1', 'b2', 'c1', 'c2']
LEVEL_LABEL = {x: x.upper() for x in LEVELS}
C2_ROLE_ORDER = ['instructional', 'reinforcement', 'interleaved', 'transfer', 'integration', 'checkpoint']
BANNED_LEARNER = [
    'pipeline', 'frontier lock', 'audit de', 'c2 unit', 'unité c2', 'calibration',
    'todo', 'placeholder', 'lorem ipsum', 'generated by', 'generation batch',
]


def norm(s: str) -> str:
    return unicodedata.normalize('NFKC', s or '').casefold().replace('’', "'")


def blob(path: Path) -> str:
    return subprocess.check_output(['git', 'hash-object', str(path)], text=True).strip()


def corpus_hash(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for path in paths:
        h.update(path.name.encode())
        h.update(b'\0')
        h.update(path.read_bytes())
        h.update(b'\0')
    return h.hexdigest()


def load() -> tuple[dict[str, list[dict]], list[Path]]:
    by = {}
    paths = []
    for level in LEVELS:
        path = FRENCH / level / 'passages.jsonl'
        paths.append(path)
        by[level] = [json.loads(x) for x in path.read_text(encoding='utf-8').splitlines() if x.strip()]
    return by, paths


def result(name: str, errors: list[str], metrics=None, notes=None) -> dict:
    return {
        'name': name,
        'status': 'PASS' if not errors else 'FAIL',
        'error_count': len(errors),
        'errors': errors[:250],
        'metrics': metrics or {},
        'notes': notes or [],
    }


def learner_strings(row: dict) -> list[str]:
    out = [row.get('title', ''), row.get('text', '')]
    out.extend(q.get('prompt', '') for q in row.get('questions', []))
    out.extend(a.get('answer', '') for a in row.get('answer_key', []))
    out.extend(a.get('explanation', '') for a in row.get('answer_key', []))
    return out


def actual_occurrences(text: str, form: str) -> int:
    # Accent/case tolerant literal form count.  Boundaries prevent short targets
    # such as 'or' from matching inside unrelated longer words.
    t, f = norm(text), norm(form)
    if not f:
        return 0
    return len(re.findall(r'(?<!\w)' + re.escape(f) + r'(?!\w)', t, flags=re.UNICODE))


def main() -> None:
    by, paths = load()
    rows = [r for level in LEVELS for r in by[level]]
    schema = json.loads(SCHEMA.read_text(encoding='utf-8'))
    validator = Draft202012Validator(schema)
    passes = []

    # 1. Schema and record integrity.
    errors = []
    ids = []
    for row in rows:
        rid = row.get('id', '<missing>')
        ids.append(rid)
        for e in sorted(validator.iter_errors(row), key=lambda x: list(x.path)):
            errors.append(f'{rid}: schema: {e.message}')
        if row.get('language') != 'fr':
            errors.append(f'{rid}: language != fr')
    dup_ids = [k for k, v in Counter(ids).items() if v > 1]
    errors.extend(f'duplicate passage id: {x}' for x in dup_ids)
    passes.append(result('01_schema_and_record_integrity', errors, {'records': len(rows), 'unique_ids': len(set(ids))}))

    # 2. Full grid, sequence, and unit continuity.
    errors = []
    grids = {}
    for level in LEVELS:
        rs = by[level]
        seq = [x.get('sequence') for x in rs]
        units = Counter(x.get('unit') for x in rs)
        grids[level] = {'passages': len(rs), 'units': dict(sorted(units.items()))}
        if len(rs) != 60:
            errors.append(f'{level}: expected 60 passages, got {len(rs)}')
        if seq != list(range(1, 61)):
            errors.append(f'{level}: sequence is not exact 1..60 in canonical order')
        if sorted(units) != list(range(1, 11)) or any(units[u] != 6 for u in range(1, 11)):
            errors.append(f'{level}: expected units 1..10 with 6 passages each, got {dict(units)}')
        for u in range(1, 11):
            expected = {f'fr-{level}-u{u:02d}-p{p:02d}' for p in range(1, 7)}
            actual = {x['id'] for x in rs if x.get('unit') == u}
            if actual != expected:
                errors.append(f'{level} unit {u}: passage-id grid mismatch')
    if len(rows) != 360:
        errors.append(f'whole French corpus expected 360 passages, got {len(rows)}')
    passes.append(result('02_grid_sequence_and_unit_continuity', errors, {'levels': grids, 'total': len(rows)}))

    # 3. Question/answer cardinality and bidirectional linkage.
    errors = []
    q_total = a_total = 0
    for row in rows:
        rid = row['id']; qs = row.get('questions', []); ans = row.get('answer_key', [])
        q_total += len(qs); a_total += len(ans)
        if len(qs) != 10: errors.append(f'{rid}: expected 10 questions, got {len(qs)}')
        if len(ans) != 10: errors.append(f'{rid}: expected 10 answers, got {len(ans)}')
        qids = [q.get('id') for q in qs]; aids = [a.get('id') for a in ans]
        if len(qids) != len(set(qids)): errors.append(f'{rid}: duplicate local question ids')
        if len(aids) != len(set(aids)): errors.append(f'{rid}: duplicate local answer ids')
        amap = {a.get('id'): a for a in ans}; qmap = {q.get('id'): q for q in qs}
        for q in qs:
            a = amap.get(q.get('answer_id'))
            if not a: errors.append(f"{rid}: {q.get('id')} answer_id missing")
            elif a.get('question_id') != q.get('id'): errors.append(f"{rid}: {q.get('id')} <-> {a.get('id')} backlink mismatch")
        for a in ans:
            q = qmap.get(a.get('question_id'))
            if not q: errors.append(f"{rid}: {a.get('id')} question_id missing")
            elif q.get('answer_id') != a.get('id'): errors.append(f"{rid}: {a.get('id')} <-> {q.get('id')} backlink mismatch")
    if q_total != 3600 or a_total != 3600:
        errors.append(f'whole French Q/A expected 3600/3600, got {q_total}/{a_total}')
    passes.append(result('03_question_answer_cardinality_and_linkage', errors, {'questions': q_total, 'answers': a_total}))

    # 4. Word-count integrity and CEFR progression.
    errors = []
    medians = {}
    ranges = {}
    for level in LEVELS:
        counts = []
        for row in by[level]:
            actual = len(row['text'].split())
            counts.append(actual)
            if actual != row.get('word_count'):
                errors.append(f"{row['id']}: word_count stored={row.get('word_count')} actual={actual}")
            if level == 'c2' and not 700 <= actual <= 1200:
                errors.append(f"{row['id']}: C2 word band {actual} outside 700..1200")
        medians[level] = statistics.median(counts)
        ranges[level] = [min(counts), max(counts)]
    for a, b in zip(LEVELS, LEVELS[1:]):
        if medians[b] <= medians[a]:
            errors.append(f'progression median not increasing: {a}={medians[a]} -> {b}={medians[b]}')
    passes.append(result('04_word_count_and_cefr_length_progression', errors, {'median_words': medians, 'ranges': ranges}))

    # 5. Lexical identity, source metadata, and first-introduction uniqueness.
    errors = []
    introduced: dict[str, tuple[str, str]] = {}
    introduced_forms: dict[str, str] = {}
    new_total = 0
    ordered = rows
    for row in ordered:
        for t in row.get('new_lexical_targets', []):
            new_total += 1
            tid, form = t.get('id'), t.get('form')
            nf = norm(form)
            if not t.get('first_introduced'):
                errors.append(f"{row['id']}: new target {tid} first_introduced is not true")
            if tid in introduced:
                errors.append(f"{row['id']}: target id reintroduced {tid}; first={introduced[tid][0]}")
            else:
                introduced[tid] = (row['id'], form)
            if nf in introduced_forms and introduced_forms[nf] != tid:
                errors.append(f"{row['id']}: target form reintroduced under new id {form}: {introduced_forms[nf]} -> {tid}")
            else:
                introduced_forms[nf] = tid
            rank = t.get('source_rank'); lex = t.get('source_lexicon')
            if rank is not None and (not isinstance(rank, int) or rank < 1):
                errors.append(f"{row['id']}: invalid source_rank for {tid}: {rank}")
            if lex is not None and lex not in {'french_top1000.csv', 'french_top3000.csv'}:
                errors.append(f"{row['id']}: unexpected source lexicon for {tid}: {lex}")
            if row.get('cefr') == 'C2':
                if lex != 'french_top3000.csv' or not isinstance(rank, int) or rank <= 1000:
                    errors.append(f"{row['id']}: C2 new target {tid} is not validated rank-1001+ top3000")
    passes.append(result('05_lexical_identity_and_source_provenance', errors, {'new_targets': new_total, 'unique_target_ids': len(introduced)}))

    # 6. Review provenance and question target references.
    errors = []
    seen = {}
    review_total = 0
    for row in ordered:
        row_targets = {t.get('id') for t in row.get('new_lexical_targets', []) + row.get('review_lexical_targets', [])}
        for t in row.get('review_lexical_targets', []):
            review_total += 1
            tid = t.get('id')
            if tid not in seen:
                errors.append(f"{row['id']}: review target {tid} has no earlier introduction")
            elif norm(t.get('form')) != norm(seen[tid]):
                errors.append(f"{row['id']}: review form mismatch for {tid}: {t.get('form')} vs {seen[tid]}")
        for q in row.get('questions', []):
            for tid in q.get('target_ids', []):
                if tid not in row_targets:
                    errors.append(f"{row['id']}: question {q.get('id')} target {tid} not present in row target sets")
        for t in row.get('new_lexical_targets', []):
            seen[t.get('id')] = t.get('form')
    passes.append(result('06_review_provenance_and_question_target_links', errors, {'review_targets': review_total}))

    # 7. Learner-text lexical exposure.
    errors = []
    checked = 0
    for row in rows:
        text = row['text']
        for t in row.get('new_lexical_targets', []):
            checked += 1
            actual = actual_occurrences(text, t.get('form', ''))
            declared = t.get('exposures_in_text', 1)
            if actual < 1:
                errors.append(f"{row['id']}: new target absent from learner text: {t.get('form')}")
            elif isinstance(declared, int) and actual < declared:
                errors.append(f"{row['id']}: target {t.get('form')} actual exposure {actual} < declared {declared}")
        for t in row.get('review_lexical_targets', []):
            checked += 1
            if t.get('representation') == 'running_text' and actual_occurrences(text, t.get('form', '')) < 1:
                errors.append(f"{row['id']}: running-text review absent: {t.get('form')}")
    passes.append(result('07_lexical_exposure_and_review_visibility', errors, {'target_checks': checked}))

    # 8. Learner-facing meta-language and placeholder hygiene.
    errors = []
    for row in rows:
        combined = '\n'.join(learner_strings(row))
        n = norm(combined)
        for bad in BANNED_LEARNER:
            if bad in n:
                errors.append(f"{row['id']}: learner-facing banned fragment {bad!r}")
        if re.search(r'fr-(?:rank|c2|a1|a2|b1|b2|c1)-', combined, re.I):
            errors.append(f"{row['id']}: internal target/passage identifier leaked learner-facing")
    passes.append(result('08_learner_facing_meta_and_placeholder_hygiene', errors))

    # 9. Exact duplicate and template-collision audit.
    errors = []
    text_map = defaultdict(list); title_map = defaultdict(list); prefix_map = defaultdict(list)
    for row in rows:
        nt = re.sub(r'\s+', ' ', norm(row['text'])).strip()
        text_map[nt].append(row['id'])
        title_map[norm(row['title']).strip()].append(row['id'])
        prefix = ' '.join(nt.split()[:28])
        if prefix: prefix_map[prefix].append(row['id'])
    for k, v in text_map.items():
        if len(v) > 1: errors.append(f'exact duplicate passage text: {v}')
    for k, v in title_map.items():
        if len(v) > 1: errors.append(f'exact duplicate title: {v}')
    suspicious_prefixes = [v for v in prefix_map.values() if len(v) >= 3]
    if suspicious_prefixes:
        errors.extend(f'repeated 28-word opening template across >=3 passages: {v}' for v in suspicious_prefixes)
    passes.append(result('09_duplicate_and_template_collision', errors, {'exact_text_duplicates': sum(len(v)>1 for v in text_map.values()), 'suspicious_opening_groups': len(suspicious_prefixes)}))

    # 10. C2 unit role order, new-target cadence, and checkpoint contract.
    errors = []
    c2 = by['c2']
    for u in range(1, 11):
        unit = [r for r in c2 if r['unit'] == u]
        types = [r['passage_type'] for r in unit]
        if types != C2_ROLE_ORDER:
            errors.append(f'C2 unit {u}: role order {types} != {C2_ROLE_ORDER}')
        for idx, row in enumerate(unit, start=1):
            tag = f"unit_role:{row['passage_type']}"
            if tag not in row.get('reader_tags', []):
                errors.append(f"{row['id']}: reader_tags missing {tag}")
            if idx <= 5 and len(row.get('new_lexical_targets', [])) != 5:
                errors.append(f"{row['id']}: standard passage expected 5 new targets, got {len(row.get('new_lexical_targets', []))}")
            if idx == 6 and row.get('new_lexical_targets'):
                errors.append(f"{row['id']}: checkpoint must be zero-new")
        new_forms = [norm(t['form']) for row in unit[:5] for t in row.get('new_lexical_targets', [])]
        if len(new_forms) != 25 or len(set(new_forms)) != 25:
            errors.append(f'C2 unit {u}: expected 25 unique standard-passage new forms')
        checkpoint_review = {norm(t['form']) for t in unit[5].get('review_lexical_targets', [])}
        if checkpoint_review != set(new_forms):
            errors.append(f'C2 unit {u}: checkpoint review set != current unit 25 new forms')
    passes.append(result('10_c2_role_lexical_and_checkpoint_contract', errors, {'units': 10}))

    # 11. Paired-text structure and capstone coherence contract.
    errors = []
    groups = defaultdict(list)
    for row in rows:
        if row.get('paired_text_group'):
            groups[row['paired_text_group']].append(row)
    for gid, members in groups.items():
        if len(members) != 2:
            errors.append(f'paired group {gid}: expected exactly 2 passages, got {[x["id"] for x in members]}')
        if len({x.get('unit') for x in members}) != 1 or len({x.get('cefr') for x in members}) != 1:
            errors.append(f'paired group {gid}: members cross CEFR/unit unexpectedly')
    u10 = {r['id']: r for r in c2 if r['unit'] == 10}
    expected_pair = 'fr-c2-u10-shared-case-viewpoints'
    if u10['fr-c2-u10-p02'].get('paired_text_group') is not None:
        errors.append('Unit10 P02 must not be in the explicit paired-text group')
    for pid in ['fr-c2-u10-p03', 'fr-c2-u10-p04']:
        if u10[pid].get('paired_text_group') != expected_pair:
            errors.append(f'{pid}: expected paired group {expected_pair}')
    if {x['id'] for x in groups.get(expected_pair, [])} != {'fr-c2-u10-p03', 'fr-c2-u10-p04'}:
        errors.append('Unit10 shared-case pair must be exactly P03/P04')
    if 'même projet fictif' not in norm(u10['fr-c2-u10-p04']['text']):
        errors.append('Unit10 P04 does not explicitly anchor to the same fictional proposal as P03')
    passes.append(result('11_paired_text_structure_and_capstone_coherence', errors, {'paired_groups': {k: [x['id'] for x in v] for k,v in groups.items()}}))

    # 12. Confirmed deferred qualitative findings must be repaired.
    errors = []
    c2id = {r['id']: r for r in c2}
    expected_roles = {
        'fr-c2-u04-p03': 'interleaved', 'fr-c2-u04-p04': 'transfer',
        'fr-c2-u05-p03': 'interleaved', 'fr-c2-u05-p04': 'transfer',
    }
    for pid, role in expected_roles.items():
        if c2id[pid]['passage_type'] != role:
            errors.append(f'{pid}: deferred role repair missing; expected {role}')
    if norm(c2id['fr-c2-u05-p01']['genre']) == 'literary prose':
        errors.append('fr-c2-u05-p01: deferred genre repair missing (analytical commentary mislabeled literary prose)')
    r = c2id['fr-c2-u06-p04']
    rt = norm(r['text'])
    if 'fichier reçu' in rt or 'document « reçu »' in rt or 'document "reçu"' in rt:
        errors.append('fr-c2-u06-p04: reçu still used as received participle/adjective rather than noun receipt')
    if 'un reçu' not in rt and 'un « reçu »' not in rt:
        errors.append('fr-c2-u06-p04: noun sense un reçu not established in learner text')
    a9 = next((a for a in r['answer_key'] if a.get('id') == 'a9'), {})
    if 'un reçu' not in norm(a9.get('answer', '')) and 'un « reçu »' not in norm(a9.get('answer', '')):
        errors.append('fr-c2-u06-p04: linked vocabulary answer does not define noun receipt sense')
    passes.append(result('12_deferred_quality_findings_resolution', errors))

    # 13. Adversarial formatting, corruption, and hidden-workflow leakage.
    errors = []
    for row in rows:
        for field, text in [('title', row.get('title','')), ('text', row.get('text',''))]:
            if '\x00' in text or '\ufffd' in text:
                errors.append(f"{row['id']}: {field} contains corruption marker")
            if '```' in text or '\t' in text:
                errors.append(f"{row['id']}: {field} contains code-fence/tab artifact")
            if '\n\n\n' in text:
                errors.append(f"{row['id']}: {field} contains excessive blank-line artifact")
        if not row.get('title','').strip() or not row.get('text','').strip():
            errors.append(f"{row['id']}: empty title/text")
        if any(not q.get('prompt','').strip() for q in row.get('questions', [])):
            errors.append(f"{row['id']}: empty question prompt")
        if any(not a.get('answer','').strip() for a in row.get('answer_key', [])):
            errors.append(f"{row['id']}: empty answer")
    passes.append(result('13_adversarial_formatting_and_corruption', errors))

    # 14. Genre/topic diversity and progression sanity.
    errors = []
    metrics = {}
    for level in LEVELS:
        genres = Counter(norm(r.get('genre','')) for r in by[level])
        topics = Counter(t for r in by[level] for t in r.get('topics', []))
        metrics[level] = {'genre_count': len(genres), 'topic_count': len(topics), 'top_genres': genres.most_common(5)}
        if level in {'b2','c1','c2'} and len(genres) < 4:
            errors.append(f'{level}: insufficient genre diversity ({len(genres)})')
        if len(topics) < 10:
            errors.append(f'{level}: insufficient topic diversity ({len(topics)})')
    passes.append(result('14_genre_topic_diversity_and_progression_sanity', errors, metrics))

    # 15. Quality-metadata completeness (status may remain generation-era until
    # a separate approval normalization step; the audit checks the structure,
    # not a self-declared approval flag).
    errors = []
    states = Counter()
    required_q = ['status','schema_check','linguistic_review','pedagogical_review','answer_key_check','coverage_check','fact_check']
    for row in rows:
        q = row.get('quality', {})
        states[q.get('status')] += 1
        for key in required_q:
            if key not in q:
                errors.append(f"{row['id']}: quality metadata missing {key}")
    passes.append(result('15_quality_metadata_completeness', errors, {'quality_statuses': dict(states)}, notes=['Generation-era draft/pending values are reported, not accepted as proof of final quality; final approval is bound to this independent audit artifact.']))

    failed = [p['name'] for p in passes if p['status'] != 'PASS']
    artifact = {
        'status': 'PASS' if not failed else 'FAIL',
        'language': 'fr',
        'scope': 'whole French A1-C2 final audit',
        'audit_pass_count': len(passes),
        'required_minimum_passes': 10,
        'canonical_passages': len(rows),
        'questions': sum(len(r.get('questions', [])) for r in rows),
        'answers': sum(len(r.get('answer_key', [])) for r in rows),
        'level_blobs': {level: blob(FRENCH/level/'passages.jsonl') for level in LEVELS},
        'whole_corpus_sha256': corpus_hash(paths),
        'failed_passes': failed,
        'passes': passes,
        'approval_ready': not failed and len(passes) >= 10,
        'note': 'This artifact supersedes generation-frontier seals for final whole-French approval while preserving those seals as historical provenance.',
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(artifact, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'status': artifact['status'], 'audit_pass_count': len(passes), 'failed_passes': failed, 'whole_corpus_sha256': artifact['whole_corpus_sha256']}, ensure_ascii=False, indent=2))
    if failed:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
